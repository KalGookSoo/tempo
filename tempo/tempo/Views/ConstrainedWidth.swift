import SwiftUI

/// 아이패드 가로 모드처럼 화면이 넓을 때, 정보 제공 위주 화면(프로그램 목록/상세/수정,
/// 설정 등)의 콘텐츠가 화면 폭 그대로 늘어나지 않도록 태블릿 세로 폭(768pt) 정도로
/// 제한하고 가운데 정렬한다. 타이머/스톱워치/인터벌 실행처럼 화면 전체를 쓰는 화면에는
/// 적용하지 않는다.
///
/// `tempoApp`의 `TabView` 루트 하나에 적용해봤지만(이슈 #45), 자식 뷰는 부모가 이미
/// 제한한 프레임보다 넓어질 수 없어서 실행 화면만 다시 전체 폭으로 빼는 방법이 없었다
/// (이슈 #47). 그래서 화면별로 필요한 곳에만 붙이는 방식으로 되돌렸다.
extension View {
    func constrainedWidth() -> some View {
        frame(maxWidth: 768)
            .frame(maxWidth: .infinity)
    }
}
